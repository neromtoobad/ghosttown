/** Block-letter text as an inline SVG. `cell` is the size of one square in px. */
export function pixelText(text: string, cell = 8, color = 'currentColor', gap = 1): SVGSVGElement {
  const chars = text.toUpperCase().split('');
  let x = 0; const rects: string[] = [];
  for (const ch of chars) {
    const g = F[ch] ?? F[' '];
    g.forEach((row, y) => row.split('').forEach((b, i) => { if (b === '1') rects.push(`<rect x="${(x + i) * cell}" y="${y * cell}" width="${cell - gap}" height="${cell - gap}"/>`); }));
    x += g[0].length + 1;
  }
  const w = (x - 1) * cell, h = 7 * cell;
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', `0 0 ${w} ${h}`); svg.setAttribute('role', 'img'); svg.setAttribute('aria-label', text);
  svg.setAttribute('class', 'pixel-text'); svg.style.setProperty('--ar', String(w / h));
  svg.innerHTML = `<g fill="${color}">${rects.join('')}</g>`;
  return svg;
}
